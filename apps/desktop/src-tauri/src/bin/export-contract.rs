//! Regenerates the TypeScript contract (GEN-1).
//!
//! Run: `cargo run -p devdesk-app --bin export-contract`
//!
//! This lives in the host package rather than in `devdesk-ipc` for a platform
//! reason, not an architectural one: on Windows, `tauri-build` generates the
//! application manifest that a Tauri-linked binary needs in order to load. A
//! standalone binary in a library crate has no manifest and fails at load with
//! STATUS_ENTRYPOINT_NOT_FOUND before `main` runs.
//!
//! The contract itself is still owned by `devdesk-ipc`; this is only its runner.

// EM-1 prohibits unwrap/expect in *non-test* code. This is a build-time codegen
// tool whose only correct failure mode is a loud one — a silently half-written
// contract is exactly what the diff gate exists to prevent.
#![allow(clippy::expect_used)]

const HEADER: &str = "\
// AUTOGENERATED — DO NOT EDIT.
//
// Regenerate: cargo run -p devdesk-app --bin export-contract
//
// GEN-1: this file is generated output. Hand edits are prohibited; CI
// regenerates and fails on diff (GEN-2). The Rust command signatures in
// crates/devdesk-ipc are the definitional API (DD-003).";

fn main() {
    // Anchored to the manifest directory, not the working directory: `cargo run`
    // executes with the caller's CWD, so a relative path here silently writes
    // outside the repository.
    let out = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../../packages/contracts/src/generated/contract.ts");

    devdesk_ipc::builder()
        .export(
            specta_typescript::Typescript::default().header(HEADER),
            &out,
        )
        .expect("failed to export TypeScript contract");

    println!("contract exported to packages/contracts/src/generated/contract.ts");
}
